#include <iostream>
using namespace std;

int main(){
    bool prime(n=1) = {1};
    int count = 0;

    prime[0] = prime[1] = 0;

    for(int i = 2; i <=n; i ++){

        if (prime[i] == true){
            count++;

            for(int j = 2*i; j <= i*i; j+i){
                prime[] == 0;
            }
        }
        
    }
    return count;
}